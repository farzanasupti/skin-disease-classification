#!/usr/bin/env python
"""Summarise the split-inflation experiment (scripts/run_inflation.py).

    python scripts/analyze_inflation.py --out-dir outputs_inflation --paper-dir paper_generated

Writes <out-dir>/results/inflation_runs.csv (one row per run), inflation_summary.csv
(mean and SD over seeds per scheme and model, and pooled over models), and, with
--paper-dir, tables/inflation.tex plus numbers_inflation.tex with \\res{infl-<scheme>}{<metric>}
macros (the same lookup as numbers.tex).

--extra-dirs adds runs from other output directories (e.g. probe_inflation.py) to the
per-model table rows and to per-model macros \\res{infl-<scheme>-<model>}{<metric>}, but not
to the pooled \\res{infl-<scheme>}{...} numbers, which stay those of --out-dir.
"""

from __future__ import annotations

import argparse
import glob
import json
import os

import sys

import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
from skinclf.data import augmentation_families, source_stem  # noqa: E402

SCHEME_LABEL = {"image": "By image", "hash": "Perceptual-hash groups", "photo": "Source-photograph groups"}
MODEL_LABEL = {"DINOv2probe": "DINOv2 probe$^a$"}
PROBE_NOTE = ("\\begin{flushleft}\n$^a$ Logistic regression on frozen DINOv2 ViT-S/14 features "
              "(images resized to a short side of 224 pixels), not a trained network; see Methods.\n"
              "\\end{flushleft}\n")
METRICS = ("acc_internal", "acc_internal_originals", "acc_unseen", "gap", "gap_originals",
           "internal_test_images_with_photo_in_train")
COUNTS = ("train_photos",)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--out-dir", default="outputs_inflation")
    p.add_argument("--paper-dir", default=None)
    p.add_argument("--extra-dirs", nargs="*", default=[], help="more run directories: table rows only")
    args = p.parse_args()

    df = load_runs(args.out_dir)
    extra = pd.concat([load_runs(d) for d in args.extra_dirs]) if args.extra_dirs else df.iloc[:0]
    res = os.path.join(args.out_dir, "results")
    os.makedirs(res, exist_ok=True)
    df.to_csv(os.path.join(res, "inflation_runs.csv"), index=False)

    by_model = df.groupby(["scheme", "model"])[list(METRICS)].agg(["mean", "std", "count"])
    pooled = df.groupby("scheme")[list(METRICS)].agg(["mean", "std", "count"])
    pooled.index = pd.MultiIndex.from_tuples([(s, "all models") for s in pooled.index], names=["scheme", "model"])
    summary = pd.concat([by_model, pooled]).sort_index()
    summary.to_csv(os.path.join(res, "inflation_summary.csv"))
    with pd.option_context("display.width", 200, "display.max_columns", 50):
        print(summary.round(3))

    if args.paper_dir:
        write_paper(df, pooled, args.paper_dir, extra)


def load_runs(out_dir):
    rows = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(out_dir, "runs", "*", "summary.json")))]
    if not rows:
        raise SystemExit(f"no finished runs in {out_dir}")
    df = pd.DataFrame(rows)
    df["gap"] = df["acc_internal"] - df["acc_unseen"]
    df["gap_originals"] = df["acc_internal_originals"] - df["acc_unseen"]
    photos = train_photos(out_dir)
    if photos:
        df["train_photos"] = [photos.get((s, int(k))) for s, k in zip(df["scheme"], df["seed"])]
    return df


def train_photos(out_dir):
    """Distinct source photographs with at least one image in each split's training part.

    The image-level split puts copies of almost every development photograph into
    training; a grouped split holds out whole photographs. Counting them shows how
    many different photographs each model learned from.
    """
    out = {}
    for path in sorted(glob.glob(os.path.join(out_dir, "splits", "*_seed*.csv"))):
        scheme, seed = os.path.basename(path)[:-4].rsplit("_seed", 1)
        sp = pd.read_csv(path)
        cls = [f.split("/")[-2] for f in sp["file"]]
        family, _ = augmentation_families([source_stem(f) for f in sp["file"]], cls)
        sp["family"] = family
        out[(scheme, int(seed))] = int(sp.loc[sp["part"] == "train", "family"].nunique())
    return out


def pct(x):
    return f"{100 * x:.1f}"


def write_paper(df, pooled, paper_dir, extra):
    os.makedirs(os.path.join(paper_dir, "tables"), exist_ok=True)
    order = [s for s in ("image", "hash", "photo") if s in set(df["scheme"])]
    lines = ["% Generated by scripts/analyze_inflation.py\n",
             "\\providecommand{\\res}[2]{\\csname res@#1@#2\\endcsname}\n"]
    for s in order:
        for m in METRICS:
            mean, sd = pooled.loc[(s, "all models"), (m, "mean")], pooled.loc[(s, "all models"), (m, "std")]
            lines.append(f"\\expandafter\\def\\csname res@infl-{s}@{m}\\endcsname{{{pct(mean)}}}\n")
            lines.append(f"\\expandafter\\def\\csname res@infl-{s}@{m}_sd\\endcsname{{{pct(sd)}}}\n")
    both = pd.concat([df, extra])
    for (s, model), d in both.groupby(["scheme", "model"]):
        for m in METRICS:
            lines.append(f"\\expandafter\\def\\csname res@infl-{s}-{model}@{m}\\endcsname{{{pct(d[m].mean())}}}\n")
    # The leak measured within one test population: internal-test originals under a
    # leaky split against the same quantity under the photograph-level split.
    if "photo" in order:
        ref = pooled.loc[("photo", "all models"), ("acc_internal_originals", "mean")]
        for s in order:
            if s != "photo":
                v = pooled.loc[(s, "all models"), ("acc_internal_originals", "mean")] - ref
                lines.append(f"\\expandafter\\def\\csname res@infl-{s}@internal_vs_photo\\endcsname{{{pct(v)}}}\n")
    if "train_photos" in df:
        for s in order:
            v = df.loc[df.scheme == s].drop_duplicates("seed")["train_photos"]
            lines.append(f"\\expandafter\\def\\csname res@infl-{s}@train_photos\\endcsname{{{v.mean():.0f}}}\n")
    lines.append(f"\\expandafter\\def\\csname res@infl@n_runs\\endcsname{{{len(df)}}}\n")
    lines.append(f"\\expandafter\\def\\csname res@infl@n_seeds\\endcsname{{{df['seed'].nunique()}}}\n")
    lines.append(f"\\expandafter\\def\\csname res@infl@n_unseen\\endcsname{{{int(df['n_unseen_photos'].iloc[0])}}}\n")
    with open(os.path.join(paper_dir, "numbers_inflation.tex"), "w") as f:
        f.writelines(lines)

    g = both.groupby(["scheme", "model"])
    rows = []
    for s in order:
        models = sorted(df.loc[df.scheme == s, "model"].unique())
        models += sorted(set(extra.loc[extra.scheme == s, "model"]) - set(models)) if len(extra) else []
        for model in models:
            d = g.get_group((s, model))
            cell = lambda c: f"{pct(d[c].mean())} $\\pm$ {pct(d[c].std())}".replace("-", "$-$", 1)
            rows.append(f"{SCHEME_LABEL[s]} & {MODEL_LABEL.get(model, model)} & {pct(d['internal_test_images_with_photo_in_train'].mean())} & "
                        f"{cell('acc_internal')} & {cell('acc_internal_originals')} & {cell('acc_unseen')} & "
                        f"{cell('gap_originals')} \\\\\n")
        rows.append("\\hline\n")
    tex = ("\\begin{table}[!ht]\n\\centering\n"
           "\\caption{\\textbf{Accuracy under three ways of splitting the same data.} "
           "Internal test: the held-out part of each split, scored on all its images (the number a study would report) "
           "and on its original photographs only. "
           "Unseen: the original photographs of the main experiment's test set, never used in any split. "
           "Test images with photo in train: share of internal-test images whose source photograph has at least one image in training. "
           "Gap: internal test (originals) minus unseen. "
           "Mean $\\pm$ SD over seeds, in \\%.}\n\\label{tab:inflation}\n\\small\n"
           "\\begin{tabular}{llrrrrr}\n\\hline\n"
           "& & \\textbf{Test images} & \\multicolumn{2}{c}{\\textbf{Internal test}} & & \\\\\n"
           "\\textbf{Split} & \\textbf{Model} & \\textbf{with photo in train} & "
           "\\textbf{All images} & \\textbf{Originals} & \\textbf{Unseen} & \\textbf{Gap} \\\\\n\\hline\n"
           + "".join(rows) + "\\end{tabular}\n" + (PROBE_NOTE if "DINOv2probe" in set(extra.get("model", [])) else "")
           + "\\end{table}\n")
    with open(os.path.join(paper_dir, "tables", "inflation.tex"), "w") as f:
        f.write(tex)


if __name__ == "__main__":
    main()
